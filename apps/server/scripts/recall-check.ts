function cosine(a: number[], b: number[]): number {
	let dot = 0;
	for (let i = 0; i < a.length; i++) dot += a[i]! * b[i]!;
	return dot; // векторы нормированы при эмбеддинге
}

async function main(): Promise<void> {
	console.log(`[recall] модель: ${MODEL}`);
	let pipeline: (text: string | string[], opts: Record<string, unknown>) => Promise<{ tolist(): number[][] }>;
	try {
		const tf = await import('@huggingface/transformers');
		pipeline = (await tf.pipeline('feature-extraction', MODEL)) as never;
	} catch (e) {
		console.error('[recall] не удалось загрузить эмбеддер:', (e as Error).message);
		console.error('[recall] нужен исходящий HTTPS к Hugging Face или зашитые веса. Пропуск.');
		process.exit(2);
	}

	const embed = async (text: string): Promise<number[]> => {
		const out = await pipeline(text, { pooling: 'mean', normalize: true });
		return out.tolist()[0]!;
	};

	console.log(`[recall] эмбеждинг ${PAIRS.length} фактов + запросов…`);
	const factVecs: number[][] = [];
	for (const p of PAIRS) factVecs.push(await embed(p.fact));
	if (factVecs[0]!.length !== DIM) console.warn(`[recall] ВНИМАНИЕ: размерность ${factVecs[0]!.length} ≠ ${DIM} (схема pgvector ждёт ${DIM})`);

	let r1 = 0;
	let r3 = 0;
	let r5 = 0;
	let mrrSum = 0;
	const misses: string[] = [];

	for (let i = 0; i < PAIRS.length; i++) {
		const q = await embed(PAIRS[i]!.query);
		const ranked = factVecs
			.map((v, j) => ({ j, score: cosine(q, v) }))
			.sort((a, b) => b.score - a.score);
		const rank = ranked.findIndex((x) => x.j === i) + 1; // 1-based
		if (rank === 1) r1++;
		if (rank <= 3) r3++;
		if (rank <= 5) r5++;
		mrrSum += 1 / rank;
		if (rank > 5) misses.push(`#${i} (ранг ${rank}): «${PAIRS[i]!.query}» → ожидался «${PAIRS[i]!.fact}»`);
	}

	const n = PAIRS.length;
	const pct = (x: number) => `${((x / n) * 100).toFixed(1)}%`;
	console.log('\n=== РУССКИЙ RECALL ЭМБЕДДЕРА ===');
	console.log(`recall@1: ${pct(r1)}  recall@3: ${pct(r3)}  recall@5: ${pct(r5)}  MRR: ${(mrrSum / n).toFixed(3)}`);
	if (misses.length) {
		console.log(`\nПромахи вне top-5 (${misses.length}):`);
		for (const m of misses) console.log('  • ' + m);
	}
	const pass = r5 / n >= 0.9 && r1 / n >= 0.6;
	console.log(`\nИТОГ: ${pass ? '✅ recall достаточен (recall@5 ≥ 90%, recall@1 ≥ 60%)' : '❌ recall ниже порога — рассмотреть смену эмбеддера (§21)'}`);
	process.exit(pass ? 0 : 1);
}

void main();
