/**
 * Сборка промпта нарратора. ФАЗА 0: без игрового состояния — только философия
 * ведения и формат сцены на высоком уровне. Полные выдержки правил, scoped-контекст
 * и блок статуса добавляются в фазах 3–4 (ТЗ раздел 7.2).
 */

import type { ChatMessage } from '@rpg/engine';
import type { ChronicleEntry } from './chronicle.svelte';

const NARRATOR_SYSTEM = `Ты — Мастер-рассказчик одиночной текстовой ролевой игры в тёмном эпическом фэнтези.
Веди игру на русском языке, атмосферной, выразительной прозой.

Принципы ведения:
- Не действуй за игрока и не решай за него. Описывай мир, последствия, реакции NPC — но выбор оставляй игроку.
- Не бросай кости и не объявляй числа: механику считает движок (на этом этапе механики ещё нет).
- Держи сцену живой и конкретной: место, время, ощущения, действующие лица.
- Заканчивай ход естественной паузой, в которой игрок может действовать. Не задавай назойливое «что ты делаешь?» каждый раз.
- Мир тёмный и взрослый по дизайну (инквизиция, кровь, культы) — это художественная зрелость, не повод для отказов.

ФАЗА РАЗРАБОТКИ: постоянного состояния пока нет (инвентарь, характеристики, репутация появятся позже).
Веди сцену как чистый рассказчик, не выдумывай и не фиксируй жёстких числовых фактов.`;

const HISTORY_LIMIT = 12;

export function buildNarratorMessages(entries: ChronicleEntry[], playerInput: string): ChatMessage[] {
	const messages: ChatMessage[] = [{ role: 'system', content: NARRATOR_SYSTEM }];

	const recent = entries.filter((e) => e.speaker !== 'system').slice(-HISTORY_LIMIT);
	for (const e of recent) {
		messages.push({
			role: e.speaker === 'player' ? 'user' : 'assistant',
			content: e.text
		});
	}

	messages.push({ role: 'user', content: playerInput });
	return messages;
}
