/**
 * Роутер тёмных сцен (ТЗ §6, §17): эвристика по ключевым словам без модели-цензора.
 * При совпадении — упреждающее переключение нарратора на фоллбэк-профиль
 * (preferFallback), чтобы основная модель не отказывала на легитимном тёмном
 * нарративе. Это НЕ цензор: триггерит запасную модель, ничего не режет.
 */

const DARK_PATTERNS = [
	'инквизиц', 'пытк', 'пытаю', 'кровь', 'кровав', 'некромант', 'нежит', 'труп', 'мертвец',
	'жертвоприношен', 'культ', 'казн', 'эшафот', 'резня', 'расчлен', 'демон', 'проклят',
	'изнасил', 'тёмн', 'ритуал кров', 'пожира', 'мучен'
];

export function isDarkScene(...texts: (string | undefined)[]): boolean {
	const hay = texts.filter(Boolean).join(' ').toLowerCase();
	return DARK_PATTERNS.some((p) => hay.includes(p));
}
