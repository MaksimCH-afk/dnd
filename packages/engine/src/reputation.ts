/**
 * Репутация и узнавание (ТЗ §9.4, creation.md шаг 2). Шкала — данные, скрыто;
 * манифестация — нарративом. Здесь — отображение скрытого счёта в уровень.
 */

import type { ReputationAxis } from './ops';
import type { ReputationTier } from './state';

/** Шкала уровней от худшего к лучшему (для индекса по порогам). */
export const TIER_SCALE: ReputationTier[] = [
	'Враг',
	'Ненавидимый',
	'Презираемый',
	'Нелюбимый',
	'Подозрительный',
	'Нейтрален',
	'Ценимый',
	'Уважаемый',
	'Почитаемый',
	'Легендарный'
];

/**
 * Композитный скрытый счёт фракции → уровень. Доверие/долг/романтика поднимают,
 * страх/вражда опускают. Нейтрален — около нуля.
 */
export function tierFromHidden(hidden: Record<ReputationAxis, number>): ReputationTier {
	const score =
		(hidden.доверие ?? 0) + (hidden.долг ?? 0) + (hidden.романтика ?? 0) - (hidden.вражда ?? 0) - (hidden.страх ?? 0) * 0.5;
	// Базовый «Нейтрален» — индекс 5. Каждые ~3 очка сдвигают на ступень.
	const idx = Math.max(0, Math.min(TIER_SCALE.length - 1, 5 + Math.round(score / 3)));
	return TIER_SCALE[idx]!;
}

/** Манифестация уровня в мире (для подсказки нарратору; не показывать игроку числом). */
export function tierEffect(tier: ReputationTier): string {
	switch (tier) {
		case 'Легендарный':
		case 'Почитаемый':
			return 'привилегии, скидки, помощь, риск за тебя';
		case 'Уважаемый':
		case 'Ценимый':
			return 'дружелюбие, скидки, доступ к редкому';
		case 'Нейтрален':
			return 'базовые услуги без проблем';
		case 'Подозрительный':
		case 'Нелюбимый':
			return 'надбавки к ценам, отказы, проверки';
		case 'Презираемый':
		case 'Ненавидимый':
			return 'вражда, доносы, нападения';
		case 'Враг':
			return 'охота, награда за голову';
	}
}
